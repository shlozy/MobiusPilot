import json
import re
from typing import Any

import httpx
from sqlalchemy.orm import Session

from app.core.config import get_settings
from app.db.models import Project, Task

settings = get_settings()


def _normalise_plan_text(raw: str) -> str:
    cleaned = raw.strip()
    if cleaned.startswith("```"):
        cleaned = re.sub(r"^```(?:json)?\s*", "", cleaned)
        cleaned = re.sub(r"\s*```\s*$", "", cleaned)
    return cleaned.strip()


def _fallback_plan(goal: str) -> dict[str, Any]:
    goal_text = goal.strip()
    tasks = [
        {
            "title": "Clarify scope and constraints",
            "description": f"Review the goal '{goal_text}' and confirm the main outcomes, dependencies, and acceptance criteria.",
            "domain": "Product",
            "priority": "high",
            "estimated_effort": "1d",
            "acceptance_criteria": ["Goal is broken into actionable deliverables.", "Dependencies and risks are identified."],
            "dependencies": [],
            "suggested_role": "Product",
            "rationale": "This is the first step to frame the work before implementation begins.",
        },
        {
            "title": "Implement the core delivery",
            "description": f"Build the primary technical work required for '{goal_text}'.",
            "domain": "Backend",
            "priority": "high",
            "estimated_effort": "2d",
            "acceptance_criteria": ["The core feature is implemented.", "Basic verification passes."],
            "dependencies": [0],
            "suggested_role": "Backend",
            "rationale": "Execution work should follow the clarified scope and dependencies.",
        },
    ]
    return {"goal": goal_text, "tasks": tasks, "source": "fallback", "rationale": "AI service unavailable; deterministic fallback plan generated."}


def generate_task_plan(db: Session, goal: str, project_id: int | None = None, context: str | None = None) -> dict[str, Any]:
    model = settings.llm_model
    if not settings.llm_api_key or not settings.llm_base_url or settings.app_env == "test":
        return _fallback_plan(goal)

    prompt = (
        "You are creating a project plan for a task orchestration platform. "
        "Return valid JSON with a top-level object containing 'goal' and 'tasks'. "
        "Each task must have title, description, domain, priority, estimated_effort, acceptance_criteria, dependencies, suggested_role, and rationale. "
        "Use a short, practical project plan."
    )
    if context:
        prompt += f" Context: {context}"
    payload = {
        "model": model,
        "max_tokens": settings.llm_max_output_tokens,
        "temperature": 0.2,
        "messages": [{"role": "user", "content": f"{prompt}\nGoal: {goal}"}],
    }

    try:
        resp = httpx.post(
            f"{settings.llm_base_url.rstrip('/')}/chat/completions",
            headers={"Authorization": f"Bearer {settings.llm_api_key}"},
            json=payload,
            timeout=settings.llm_timeout_seconds,
        )
        if resp.status_code != 200:
            raise ValueError(f"LLM returned HTTP {resp.status_code}: {resp.text[:200]}")
        data = resp.json()
        choices = data.get("choices") or []
        if not choices:
            raise ValueError("LLM response contains no choices.")
        message = choices[0].get("message") or {}
        finish_reason = data.get("choices", [{}])[0].get("finish_reason")
        content = message.get("content")
        if finish_reason == "length" and not content:
            raise ValueError("LLM response was truncated or empty; not usable for structured planning.")
        if not content or not str(content).strip():
            raise ValueError("LLM response was empty.")
        cleaned = _normalise_plan_text(content)
        parsed = json.loads(cleaned)
        if not isinstance(parsed, dict) or "tasks" not in parsed:
            raise ValueError("LLM JSON did not include a tasks array.")
        tasks = parsed["tasks"]
        if not isinstance(tasks, list) or not tasks:
            raise ValueError("LLM returned no tasks.")
        for i, task in enumerate(tasks):
            task.setdefault("dependencies", [])
            task.setdefault("acceptance_criteria", ["Task is complete and validated."])
            task.setdefault("rationale", "Generated by the LLM and reviewed by the coordinator.")
            if "estimated_effort" not in task:
                task["estimated_effort"] = "1d"
        return {"goal": parsed.get("goal", goal), "tasks": tasks, "source": "llm", "rationale": "AI-generated plan validated against the required schema."}
    except Exception:
        return _fallback_plan(goal)


def get_project_task_summary(db: Session, project_id: int) -> dict[str, Any]:
    project = db.query(Project).filter(Project.id == project_id).first()
    tasks = db.query(Task).filter(Task.project_id == project_id).all()
    return {
        "project_name": project.name if project else "Unknown",
        "task_count": len(tasks),
        "pending": sum(1 for task in tasks if task.status == "pending"),
        "in_progress": sum(1 for task in tasks if task.status == "in_progress"),
        "completed": sum(1 for task in tasks if task.status == "completed"),
    }
